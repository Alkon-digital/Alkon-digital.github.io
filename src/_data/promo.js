/* Акция в главном баннере.
   Выключить — поставить on: false. Сама по себе она погаснет после untilISO,
   но только при следующей сборке: сайт статический, по таймеру ничего не пересобирается.
   Поэтому после окончания срока нужен пуш (пусть даже пустой), иначе акция
   так и останется висеть. */
export default function () {
  const untilISO = "2026-10-31";
  const today = new Date().toISOString().slice(0, 10);

  return {
    on: true && today <= untilISO,
    untilISO,
    until: "31 октября",
    label: "Акция до 31 октября",
    title: "Разработка рекламной кампании",
    price: "от 45 000",
    unit: "₽",
    note: "Разово, бюджет площадки оплачивается отдельно. Дальше ведение по обычному прайсу.",
    cta: "Забрать до конца акции"
  };
}
